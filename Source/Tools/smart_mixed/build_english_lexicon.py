#!/usr/bin/env python3
"""Builds Source/Data/smart-mixed-english-lexicon.txt (A2).

Inputs:
  --scowl   ESDB/SCOWL v2 data file `data/scowl-pre.txt` from
            https://github.com/en-wl/wordlist (read as plain text; this script
            does not run anything from that repository).
  --terms   Source/Data/smart-mixed-tech-terms.txt (project-owned list).
  --max-size  Largest ESDB size band to include. Bands above 80 carry extra
            copyright terms (UKACD); the default 60 keeps common words only.

Output lines are "word tier", sorted case-insensitively, with the ESDB
copyright notice required by its licence at the top.
"""

import argparse
import re
import sys

WORD = re.compile(r"[A-Za-z0-9]+")

NOTICE = """# Broccoli SmartInput English lexicon for smart mixed input.
# Generated by Source/Tools/smart_mixed/build_english_lexicon.py. Do not edit;
# change smart-mixed-tech-terms.txt or the size band and regenerate.
# Format: word tier (lower tier = more common).
#
# Words with tier >= 35 come from the English Speller Database (ESDB,
# previously SCOWL), sizes {min_size}-{max_size}:
#
# Copyright 2000-2026 by Kevin Atkinson
#
# Permission to use, copy, modify, distribute, and sell any part of the English
# Speller Database (ESDB, previously known as SCOWLv2), or word lists
# created from it, is hereby granted without fee, provided that the above
# copyright notice appears in all copies and that both the above copyright
# notice and this notice appear in supporting documentation.  Kevin Atkinson
# makes no representations about the suitability of this database for any
# purpose.  It is provided "as is" without express or implied warranty.
#
"""


def parse_scowl(path, max_size):
    words = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\n")
            if not line.strip():
                continue
            head, sep, rest = line.partition(": ")
            if not sep:
                continue
            m = re.match(r"(\d+)", head)
            if not m:
                continue
            size = int(m.group(1))
            if size > max_size:
                continue
            parts = rest.split(": ")
            lemma = parts[0]
            # A single capital letter before the lemma is a variant tag.
            if len(lemma) == 1 and lemma.isupper() and len(parts) > 1:
                parts = parts[1:]
                lemma = parts[0]
            lemma = re.sub(r"\s*<[^>]*>\s*$", "", lemma).strip()
            forms = [lemma]
            if len(parts) > 1:
                forms += parts[1].split(",")
            for form in forms:
                w = form.strip().rstrip("~").strip()
                if w == "-" or not WORD.fullmatch(w):
                    continue
                key = w.lower()
                if key not in words or size < words[key][1]:
                    words[key] = (w, size)
    return words


def parse_terms(path, default_tier=30):
    terms = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            fields = line.split()
            if not fields or fields[0].startswith("#"):
                continue
            word = fields[0]
            if len(fields) == 2 and fields[1].isdigit():
                tier = int(fields[1])
            elif len(fields) == 1:
                tier = default_tier
            else:
                continue  # multi-word entries cannot be typed as one run
            if WORD.fullmatch(word):
                terms[word.lower()] = (word, tier)
    return terms


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--scowl", required=True)
    parser.add_argument("--terms", required=True)
    parser.add_argument("--max-size", type=int, default=60)
    parser.add_argument("--min-length", type=int, default=2)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()

    words = parse_scowl(args.scowl, args.max_size)
    for key, (term, tier) in parse_terms(args.terms).items():
        existing = words.get(key)
        # Brand names that are also everyday words (line, word, zoom, slack)
        # keep the everyday lowercase spelling; only the tier is raised.
        if existing and existing[0].islower() and existing[1] <= 50:
            words[key] = (existing[0], min(tier, existing[1]))
        else:
            words[key] = (term, tier)
    entries = sorted(
        ((w, t) for k, (w, t) in words.items() if len(k) >= args.min_length),
        key=lambda e: (e[0].lower(), e[0]),
    )
    with open(args.output, "w", encoding="utf-8") as out:
        out.write(NOTICE.format(min_size=35, max_size=args.max_size))
        for w, t in entries:
            out.write(f"{w} {t}\n")
    print(f"wrote {len(entries)} words to {args.output}", file=sys.stderr)


if __name__ == "__main__":
    main()
